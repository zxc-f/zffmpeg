/// The default Macintosh color table of `bit_depth` (1, 2, 4 or 8) bits.
pub fn defaultPalette(bit_depth: u5) []const u8 {
    return switch (bit_depth) {
        1 => &qt_default_palette_2,
        2 => &qt_default_palette_4,
        4 => &qt_default_palette_16,
        else => &qt_default_palette_256,
    };
}

/// av_color_primaries_name is not null.
pub fn knownPrimaries(v: u16) bool {
    return v <= 12 or v == 22 or v == 256;
}

/// av_color_transfer_name is not null.
pub fn knownTransfer(v: u16) bool {
    return v <= 18 or v == 256;
}

/// av_color_space_name is not null.
pub fn knownSpace(v: u16) bool {
    return v <= 17;
}

/// `AVCOL_*_UNSPECIFIED` of the three color enums.
pub const unspecified_color: u16 = 2;

/// tkhd's matrix after the movie's (each product shifted by its column's
/// fixed point, summed into an int as C does), or null for the identity.
pub fn displayMatrix(track: [3][3]i32, movie: [3][3]i32) ?[9]i32 {
    const sh = [3]u6{ 16, 16, 30 };
    var res: [3][3]i32 = @splat(@splat(0));
    for (0..3) |i| {
        for (0..3) |j| {
            for (0..3) |e| {
                const product = @as(i64, track[i][e]) * movie[e][j];
                // `int += int64_t`: the sum truncated to int.
                res[i][j] = @truncate(@as(i64, res[i][j]) + (product >> sh[e]));
            }
        }
    }
    const identity = res[0][0] == 1 << 16 and res[1][1] == 1 << 16 and res[2][2] == 1 << 30 and
        res[0][1] == 0 and res[0][2] == 0 and res[1][0] == 0 and res[1][2] == 0 and res[2][0] == 0 and res[2][1] == 0;
    if (identity) return null;
    var out: [9]i32 = undefined;
    for (0..3) |i| for (0..3) |j| {
        out[i * 3 + j] = res[i][j];
    };
    return out;
}

/// mov_read_tkhd's sample aspect ratio from the display matrix's scale,
/// when the track has a size and the scales differ by more than 1%.
pub fn matrixAspect(m: [9]i32, width: i32, height: i32) ?rational.Rational {
    if (width == 0 or height == 0) return null;
    var t: [2]f64 = undefined;
    for (0..2) |i| t[i] = libm.hypot(@floatFromInt(m[0 + i]), @floatFromInt(m[3 + i]));
    const limit: f64 = 1 << 24;
    if (t[0] > 1 and t[1] > 1 and t[0] < limit and t[1] < limit and @abs(t[0] / t[1] - 1.0) > 0.01)
        return rational.fromFloat(t[0] / t[1], std.math.maxInt(i32));
    return null;
}

/// clap's crop as FRAME_CROPPING's four little-endian 32-bit values (top,
/// bottom, left, right), null where FFmpeg sets none (no crop, or an
/// invalid box, which it ignores).
pub fn clapCropping(width: i32, height: i32, fields: [8]i32) ?[16]u8 {
    var aperture_width: rational.Rational = .{ .num = fields[0], .den = fields[1] };
    var aperture_height: rational.Rational = .{ .num = fields[2], .den = fields[3] };
    const horiz_off: rational.Rational = .{ .num = fields[4], .den = fields[5] };
    const vert_off: rational.Rational = .{ .num = fields[6], .den = fields[7] };
    if (aperture_width.num < 0 or aperture_width.den <= 0 or aperture_height.num < 0 or aperture_height.den <= 0 or
        horiz_off.den <= 0 or vert_off.den <= 0) return null;
    if (rational.cmp(.{ .num = width, .den = 1 }, aperture_width) < 0 or
        rational.cmp(.{ .num = height, .den = 1 }, aperture_height) < 0) return null;
    const half: rational.Rational = .{ .num = 1, .den = 2 };
    // `width - 1` and `height - 1` as C's int arithmetic wraps.
    const pc_x = rational.add(rational.mul(.{ .num = width -% 1, .den = 1 }, half), horiz_off);
    const pc_y = rational.add(rational.mul(.{ .num = height -% 1, .den = 1 }, half), vert_off);
    aperture_width = rational.mul(rational.sub(aperture_width, .{ .num = 1, .den = 1 }), half);
    aperture_height = rational.mul(rational.sub(aperture_height, .{ .num = 1, .den = 1 }), half);
    const left = toInt64(rational.sub(pc_x, aperture_width));
    var right = toInt64(rational.add(pc_x, aperture_width));
    const top = toInt64(rational.sub(pc_y, aperture_height));
    var bottom = toInt64(rational.add(pc_y, aperture_height));
    if (top < 0 or bottom < 0 or bottom > @as(i64, height) - 1 or left < 0 or right < 0 or right > @as(i64, width) - 1) return null;
    bottom = @as(i64, height) - 1 - bottom;
    right = @as(i64, width) - 1 - right;
    if (left | right | top | bottom == 0) return null;
    if (left + right >= width or top + bottom >= height) return null;
    var out: [16]u8 = undefined;
    // AV_WL32A of int64_t values: their low 32 bits.
    std.mem.writeInt(u32, out[0..4], @truncate(@as(u64, @bitCast(top))), .little);
    std.mem.writeInt(u32, out[4..8], @truncate(@as(u64, @bitCast(bottom))), .little);
    std.mem.writeInt(u32, out[8..12], @truncate(@as(u64, @bitCast(left))), .little);
    std.mem.writeInt(u32, out[12..16], @truncate(@as(u64, @bitCast(right))), .little);
    return out;
}

/// `int64_t x = av_q2d(q)`: toward zero. Every rational here has a
/// positive denominator of at most INT_MAX and a numerator in int's range,
/// so the quotient is within ±2^31.
fn toInt64(q: rational.Rational) i64 {
    std.debug.assert(q.den != 0);
    return @trunc(q.toFloat());
}

fn putRational(out: []u8, q: rational.Rational) void {
    std.mem.writeInt(i32, out[0..4], q.num, .little);
    std.mem.writeInt(i32, out[4..8], q.den, .little);
}

/// AVMasteringDisplayMetadata: the primaries (three pairs), the white
/// point, the minimum and maximum luminance, then has_primaries and
/// has_luminance, both set.
pub fn masteringDisplay(primaries: [3][2]rational.Rational, white: [2]rational.Rational, min_luminance: rational.Rational, max_luminance: rational.Rational) [88]u8 {
    var out: [88]u8 = @splat(0);
    for (0..3) |i| for (0..2) |j| putRational(out[(i * 2 + j) * 8 ..][0..8], primaries[i][j]);
    putRational(out[48..56], white[0]);
    putRational(out[56..64], white[1]);
    putRational(out[64..72], min_luminance);
    putRational(out[72..80], max_luminance);
    std.mem.writeInt(i32, out[80..84], 1, .little);
    std.mem.writeInt(i32, out[84..88], 1, .little);
    return out;
}

/// AVContentLightMetadata: MaxCLL and MaxFALL, unsigned.
pub fn contentLight(max_cll: u16, max_fall: u16) [8]u8 {
    var out: [8]u8 = undefined;
    std.mem.writeInt(u32, out[0..4], max_cll, .little);
    std.mem.writeInt(u32, out[4..8], max_fall, .little);
    return out;
}

/// AVAmbientViewingEnvironment: the illuminance and the light's x and y.
pub fn ambientViewing(illuminance: rational.Rational, x: rational.Rational, y: rational.Rational) [24]u8 {
    var out: [24]u8 = undefined;
    putRational(out[0..8], illuminance);
    putRational(out[8..16], x);
    putRational(out[16..24], y);
    return out;
}

/// ff_isom_parse_dvcc_dvvc's AVDOVIDecoderConfigurationRecord from the
/// box's first bytes (at least 4).
pub fn doviConfig(buf: []const u8) [9]u8 {
    std.debug.assert(buf.len >= 4);
    const bits = @as(u16, buf[2]) << 8 | buf[3];
    var out: [9]u8 = .{
        buf[0],
        buf[1],
        @truncate((bits >> 9) & 0x7f),
        @truncate((bits >> 3) & 0x3f),
        @truncate((bits >> 2) & 1),
        @truncate((bits >> 1) & 1),
        @truncate(bits & 1),
        0,
        0,
    };
    if (buf.len >= 5) {
        out[7] = (buf[4] >> 4) & 0x0f;
        out[8] = (buf[4] >> 2) & 0x03;
    }
    return out;
}

const testing = std.testing;

test "the display matrix: the identity is none, a rotation is kept, the movie's applies after" {
    const identity = [3][3]i32{ .{ 1 << 16, 0, 0 }, .{ 0, 1 << 16, 0 }, .{ 0, 0, 1 << 30 } };
    try testing.expectEqual(null, displayMatrix(identity, identity));
    const rotate = [3][3]i32{ .{ 0, 1 << 16, 0 }, .{ -(1 << 16), 0, 0 }, .{ 0, 0, 1 << 30 } };
    try testing.expectEqual([9]i32{ 0, 1 << 16, 0, -(1 << 16), 0, 0, 0, 0, 1 << 30 }, displayMatrix(rotate, identity).?);
    // No mvhd: a movie matrix of zeros makes every track's zeros.
    try testing.expectEqual([9]i32{ 0, 0, 0, 0, 0, 0, 0, 0, 0 }, displayMatrix(identity, @splat(@splat(0))).?);
    // A horizontal scale of 2: the aspect ratio 2.
    const wide = [9]i32{ 2 << 16, 0, 0, 0, 1 << 16, 0, 0, 0, 1 << 30 };
    try testing.expectEqual(rational.Rational{ .num = 2, .den = 1 }, matrixAspect(wide, 100, 100).?);
}

test "clap: a centered crop, no crop, and invalid boxes FFmpeg ignores" {
    // 100x80 cropped to 90x70 about the center: 5 on every side.
    const crop = clapCropping(100, 80, .{ 90, 1, 70, 1, 0, 1, 0, 1 }).?;
    try testing.expectEqualSlices(u8, &.{ 5, 0, 0, 0, 5, 0, 0, 0, 5, 0, 0, 0, 5, 0, 0, 0 }, &crop);
    try testing.expectEqual(null, clapCropping(100, 80, .{ 100, 1, 80, 1, 0, 1, 0, 1 }));
    try testing.expectEqual(null, clapCropping(100, 80, .{ 101, 1, 80, 1, 0, 1, 0, 1 }));
    try testing.expectEqual(null, clapCropping(100, 80, .{ 90, 0, 70, 1, 0, 1, 0, 1 }));
}
